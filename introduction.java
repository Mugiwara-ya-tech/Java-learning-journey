// Multiple Statement
// A line of code is called a statement. A statement performs a specific task.
// The output command is an eg of statement

// Each statement needs to end with a semicolon ;

// You can add as many statement (or line of code) as you need
public class Demo {
    public static void main(String[] args){
        System.out.println("Name :");        // O/P is Name:
        System.out.println("Surname:");      // O/P is Surname:
    }
}

// When you give the computer many statement the instructions will be executed line by line from top to bottom

// Computer treat text & numbers differently when printing text outputs you need to enclose the text in double quotes, you dont need quotes when outputting numbers

public class Demo {
    public static void main(String[] args) {
        System.out.println("Points:");        // O/P is Points:
        System.out.println(500);              // O/P is 500
    }
}

